def resolve_unfreeze_layers_for_single_layer(single_layer: int, total_layers: int, unfreeze_layer_count: int) -> List[int]:
    """
    Resolve actual unfrozen layers based on single_layer and UNFREEZE_ENCODER_LAYERS.

    Rules:
        single12 + unfree1 -> [12]
        single12 + unfree2 -> [11, 12]
        single12 + unfree4 -> [9, 10, 11, 12]
    """
    single_layer = int(single_layer)
    total_layers = int(total_layers)
    unfreeze_layer_count = int(unfreeze_layer_count)

    if not (1 <= single_layer <= total_layers):
        raise ValueError(f"single_layer={single_layer} Beyond range [1, {total_layers}]")
    if unfreeze_layer_count <= 0:
        raise ValueError("UNFREEZE_ENCODER_LAYERS Must be >= 1")

    start_layer = max(1, single_layer - unfreeze_layer_count + 1)
    end_layer = min(single_layer, total_layers)
    return list(range(start_layer, end_layer + 1))


def resolve_mask_inject_after_layer(resolved_unfreeze_layers: Sequence[int], mask_offset: int) -> int:
    """
    Automatically parsing mask injection positions according to the "first trainingable level".

    Parameters meaning:
        mask_offset=1 -> The first training layer is filled with mask.
        mask_offset=2 -> The first two levels of the training level are injected into the mask.

    Return value is actual layer index:
        For example, training layers [12], offset=1 -> after layer11; offset=2 -> after layer10.
        For example, training layer [9,10,11,12], offset=1 -> after layer8.

    If you return 0, enter before the first layer of the encoder, i. e. conv/pos embedding.
    """
    if len(resolved_unfreeze_layers) == 0:
        raise ValueError("resolved_unfreeze_layers Can't be empty.")
    mask_offset = int(mask_offset)
    if mask_offset <= 0:
        raise ValueError("STAGE3_MASK_INJECT_AFTER_LAYERS The value in the table must be >= 1.")

    first_trainable = min(int(x) for x in resolved_unfreeze_layers)
    return max(0, first_trainable - int(mask_offset))


