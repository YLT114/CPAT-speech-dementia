def repeat_or_center_crop_to_30s(x: np.ndarray, valid_len: int) -> Tuple[np.ndarray, int]:
    """
    Consistency with Stage2:
    - Short audio: repeat to 30s
    - Long audio: Centered to 30s

    Return:
        wav_30: Fixed 30s Wave
        valid_len_out: Original active length; 30s if original audio exceeds 30s
    """
    x = np.asarray(x, dtype=np.float32).reshape(-1)
    valid_len = int(max(0, min(valid_len, x.shape[0])))
    base = x[:valid_len] if valid_len > 0 else x
    L = int(base.shape[0])

    if L <= 0:
        return np.zeros((TARGET_30S_SAMPLES,), dtype=np.float32), 0

    if L >= TARGET_30S_SAMPLES:
        start = (L - TARGET_30S_SAMPLES) // 2
        seg = base[start:start + TARGET_30S_SAMPLES]
        return seg.astype(np.float32, copy=False), TARGET_30S_SAMPLES

    n_rep = TARGET_30S_SAMPLES // L
    rem = TARGET_30S_SAMPLES - n_rep * L
    out = np.tile(base, n_rep)
    if rem > 0:
        out = np.concatenate([out, base[:rem]], axis=0)
    if out.shape[0] != TARGET_30S_SAMPLES:
        out = out[:TARGET_30S_SAMPLES]
    return out.astype(np.float32, copy=False), L


def pad_or_truncate_labels(label_tensor: torch.Tensor, target_t: int = TOK_T_FULL) -> torch.Tensor:
    """
    Harmonize Stage2 label tensor to [H, target_t].
    - If it's too short, fill the right side IGNORE_INDEX
    - If it's too long, cut right.
    """
    if label_tensor.dim() == 1:
        label_tensor = label_tensor.unsqueeze(0)
    if label_tensor.dim() != 2:
        raise ValueError(f"label_tensor Must be [H,T] or [T], current shape ={tuple(label_tensor.shape)}")

    H, T = label_tensor.shape
    if T == target_t:
        return label_tensor.long()
    if T > target_t:
        return label_tensor[:, :target_t].long()

    pad = torch.full((H, target_t - T), int(IGNORE_INDEX), dtype=torch.long)
    return torch.cat([label_tensor.long(), pad], dim=1)


def make_time_mask_tok_valid(valid_mask_tok: torch.Tensor, mask_prob: float, mask_span: int) -> torch.Tensor:
    """
    Randomly generated span mask according to level token valid mask.

    Enter:
        valid_mask_tok: [B,T],True Signal valid token
    Output:
        mask: [B,T],True Says that the token is mask and needs to be cluster prediction
    """
    assert valid_mask_tok.dim() == 2
    B, T = valid_mask_tok.shape
    device = valid_mask_tok.device
    mask = torch.zeros(B, T, dtype=torch.bool, device=device)

    mask_prob = float(mask_prob)
    mask_span = int(mask_span)

    for b in range(B):
        valid_len = int(valid_mask_tok[b].long().sum().item())
        valid_len = max(1, min(valid_len, T))
        if valid_len <= 1:
            continue

        num_mask = int(math.ceil(valid_len * mask_prob))
        if num_mask <= 0:
            continue

        masked = 0
        tries = 0
        span_low = max(1, mask_span // 2)
        span_high = max(span_low + 1, int(mask_span * 1.5))

        while masked < num_mask and tries < 10 * max(1, num_mask):
            span = int(torch.randint(span_low, span_high, (1,), device=device).item())
            span = min(span, valid_len)
            start_max = max(1, valid_len - span + 1)
            start = int(torch.randint(0, start_max, (1,), device=device).item())
            end = min(valid_len, start + span)

            if mask[b, start:end].any():
                tries += 1
                continue

            mask[b, start:end] = True
            masked += (end - start)

    mask = mask & valid_mask_tok
    return mask


