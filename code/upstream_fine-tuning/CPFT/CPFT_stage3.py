def find_latest_stage3_metrics_csv(stage3_save_dir: str) -> Optional[str]:
    """
    Finds metrics.csv for output Stage3 CSVLogger.

    Current logger saving method:
        CSVLogger(save_dir=STAGE3_SAVE_DIR, name="csv_logs")

    Therefore, metrics.csv is usually located in:
        STAGE3_SAVE_DIR/csv_logs/version_*/metrics.csv
    """
    root = Path(str(stage3_save_dir))
    candidates = list(root.glob("csv_logs/version_*/metrics.csv"))
    if len(candidates) == 0:
        return None
    candidates = sorted(candidates, key=lambda p: p.stat().st_mtime, reverse=True)
    return str(candidates[0].resolve())


def _stage3_metric_series(df: pd.DataFrame, metric_name: str) -> pd.Series:
    """
    Securely remove a non-empty sequence from metric.
    """
    if df is None or metric_name not in df.columns:
        return pd.Series(dtype=float)
    return pd.to_numeric(df[metric_name], errors="coerce").dropna()


def _stage3_last_metric(df: pd.DataFrame, metric_name: str) -> Optional[float]:
    """
    Take a last non-empty value from metric.
    """
    s = _stage3_metric_series(df, metric_name)
    if len(s) == 0:
        return None
    return float(s.iloc[-1])


def _stage3_best_row_by_min_metric(df: pd.DataFrame, metric_name: str) -> Optional[pd.Series]:
    """
    Press metric_name to take the smallest value in the row.
    """
    if df is None or metric_name not in df.columns:
        return None
    tmp = df.copy()
    tmp[metric_name] = pd.to_numeric(tmp[metric_name], errors="coerce")
    tmp = tmp.dropna(subset=[metric_name])
    if len(tmp) == 0:
        return None
    return tmp.loc[tmp[metric_name].idxmin()]


def _stage3_metric_at_epoch(df: pd.DataFrame, metric_name: str, epoch: Optional[int]) -> Optional[float]:
    """
    Try to read a metric that specifies the epoch.
    returns the last non-empty value of metric if epoch does not exist.
    """
    if df is None or metric_name not in df.columns:
        return None

    tmp = df.copy()
    tmp[metric_name] = pd.to_numeric(tmp[metric_name], errors="coerce")
    tmp = tmp.dropna(subset=[metric_name])
    if len(tmp) == 0:
        return None

    if epoch is not None and "epoch" in tmp.columns:
        ep = pd.to_numeric(tmp["epoch"], errors="coerce")
        hit = tmp[ep == int(epoch)]
        if len(hit) > 0:
            return float(hit[metric_name].iloc[-1])

    return float(tmp[metric_name].iloc[-1])


def compute_random_clus_ce_baseline(num_clusters: Sequence[int]) -> float:
    """
    masked cluster prediction A random guess CE baseline.

    The single K class randomly CE is about log(K);
    Take mean(log(K_i)) at multiple ends.
    """
    ks = [int(x) for x in num_clusters]
    if len(ks) == 0:
        return float("nan")
    return float(np.mean([math.log(max(1, k)) for k in ks]))


def decide_stage3_quality(
    best_valid_clus_loss: Optional[float],
    random_ce_baseline: float,
    best_valid_utt_mae_raw: Optional[float],
    train_valid_clus_gap: Optional[float],
) -> Tuple[str, List[str], Optional[float]]:
    """
    Decision-making based on Stage3 internal indicators.

    Note:
    - This does not prove that eventually RMSE will drop;
    - It will only determine whether Stage3 is worth going down to audio_cut + quick probe.
    """
    warnings = []

    if best_valid_clus_loss is None or not np.isfinite(random_ce_baseline):
        return "reject_stage3", ["missing_valid_clus_loss_or_random_baseline"], None

    ratio = float(best_valid_clus_loss / max(1e-8, random_ce_baseline))

    if ratio < 0.90:
        decision = "go_probe"
    elif ratio < 1.00:
        decision = "warn_probe"
        warnings.append("valid_clus_loss_only_slightly_better_than_random")
    else:
        decision = "reject_stage3"
        warnings.append("valid_clus_loss_not_better_than_random")

    if best_valid_utt_mae_raw is None:
        warnings.append("missing_valid_utt_mae_raw")
        if decision == "go_probe":
            decision = "warn_probe"

    if train_valid_clus_gap is not None and train_valid_clus_gap > max(0.5, 0.3 * abs(float(best_valid_clus_loss))):
        warnings.append("large_train_valid_clus_gap")
        if decision == "go_probe":
            decision = "warn_probe"

    return decision, warnings, ratio


